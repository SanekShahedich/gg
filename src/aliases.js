export function normalizeAliasKey(text) {
  return text
    .toLowerCase()
    .replace(/[''`]/g, '')
    .replace(/ії/g, 'и')
    .replace(/і/g, 'и')
    .replace(/ї/g, 'и')
    .replace(/є/g, 'е')
    .replace(/ґ/g, 'г')
    .replace(/ё/g, 'е')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

const ALIAS_LOOKUP = Object.fromEntries(
  Object.entries(ALIASES).map(([k, id]) => [normalizeAliasKey(k), id]),
);

export function resolveAliasMalId(query) {
  return ALIAS_LOOKUP[normalizeAliasKey(query)] ?? null;
}
